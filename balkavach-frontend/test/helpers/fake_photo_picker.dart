/// 1×1 transparent PNG, valid for `Image.memory`.
final Uint8List kTinyPng = Uint8List.fromList(const [
  0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D, //
  0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
  0x08, 0x06, 0x00, 0x00, 0x00, 0x1F, 0x15, 0xC4, 0x89, 0x00, 0x00, 0x00,
  0x0D, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9C, 0x63, 0xF8, 0xFF, 0xFF, 0x3F,
  0x03, 0x00, 0x08, 0xFC, 0x02, 0xFE, 0xA7, 0x9A, 0xA0, 0xA0, 0x00, 0x00,
  0x00, 0x00, 0x49, 0x45, 0x4E, 0x44, 0xAE, 0x42, 0x60, 0x82,
]);

/// Returns canned results instead of opening the camera or gallery.
class FakePhotoPicker implements PhotoPicker {
  FakePhotoPicker({this.result, this.fails = false});

  PickedPhoto? result;
  bool fails;
  final sources = <PhotoSource>[];

  @override
  Future<PickedPhoto?> pick(PhotoSource source) async {
    sources.add(source);
    if (fails) throw const PhotoPickException();
    return result;
  }
}

PickedPhoto tinyPhoto({String name = 'proof.png'}) =>
    PickedPhoto(bytes: kTinyPng, fileName: name, mimeType: 'image/png');
