"""Regenerate docs/mission-catalogue-inventory.md from the catalogue data (so the counts cannot drift).

    python scripts/catalogue_inventory.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app.content.daily_missions import ACTIVITIES, AGE_BANDS, LOCALES, MISSIONS, variation_payload  # noqa: E402
from app.services.daily_mission_service import THEMES_BY_WEEKDAY  # noqa: E402
from app.services.mission_catalogue_service import catalogue_summary, target_problems, validate_catalogue  # noqa: E402

OUT = ROOT.parent / "docs" / "mission-catalogue-inventory.md"
DAYS = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"]
BAND = {"4_6": "4-6", "7_10": "7-10", "11_15": "11-15"}
LOCALE_NAME = {"en": "English", "gu": "Gujarati", "hi": "Hindi"}


def build() -> str:
	summary = catalogue_summary()
	problems = validate_catalogue()
	lines = [
		"# Daily mission catalogue: inventory (catalogue version `c1`)",
		"",
		"Generated by `balkavach-backend/scripts/catalogue_inventory.py` from `app/content/daily_missions/`. Do not edit by hand.",
		"",
		"## Totals",
		"",
		"| What | Count |",
		"|---|---|",
		f"| Themes (one per weekday) | {summary['themes']} |",
		f"| Mission templates | {summary['templates']} |",
		f"| Distinct activities recorded (`activities.py`) | {summary['distinct_activities']} |",
		f"| Age-specific missions (template x age band) | {summary['age_specific_missions']} |",
		f"| Localized versions stored (age band x language) | {summary['variations']} |",
		f"| English / Gujarati / Hindi versions | {summary['variations_en']} / {summary['variations_gu']} / {summary['variations_hi']} |",
		f"| Validation problems reported by `validate_catalogue()` | {len(problems)} |",
		f"| Shortfalls against the target of 6 distinct activities per theme (`target_problems()`) | {len(target_problems())} |",
		"",
		"## Templates per weekday theme",
		"",
		"| Day | Theme key | Templates | Distinct activities | Age-specific missions | Localized versions |",
		"|---|---|---|---|---|---|",
	]
	for weekday, day in enumerate(DAYS):
		theme = THEMES_BY_WEEKDAY[weekday]
		group = [m for m in MISSIONS if m["theme"] == theme]
		mechanics = {ACTIVITIES[m["slug"]]["mechanic"] for m in group if m["slug"] in ACTIVITIES}
		lines.append(f"| {day} | `{theme}` | {len(group)} | {len(mechanics)} | {len(group) * len(AGE_BANDS)} | {len(group) * len(AGE_BANDS) * len(LOCALES)} |")
	lines += [
		"",
		"## Native-speaker review status",
		"",
		"| Language | Versions | Written by | Native-speaker educator review |",
		"|---|---|---|---|",
		f"| English | {summary['variations_en']} | project authors | not applicable (plain English; no child pilot) |",
		f"| Gujarati | {summary['variations_gu']} | project authors | **NOT reviewed** (machine-checked for script, numbers and structure only) |",
		f"| Hindi | {summary['variations_hi']} | project authors | **NOT reviewed** (machine-checked for script, numbers and structure only) |",
		"",
		"Nothing here claims professional review. See `docs/mission-content-research.md`.",
		"",
		"## Themes and skills",
		"",
		"| Day | Theme key | Template slug | Type | Skill practised | Also practises | Activity (mechanic) | Evidence basis |",
		"|---|---|---|---|---|---|---|---|",
	]
	for weekday, day in enumerate(DAYS):
		theme = THEMES_BY_WEEKDAY[weekday]
		missions = [m for m in MISSIONS if m["theme"] == theme]
		if not missions:
			lines.append(f"| {day} | `{theme}` | **none** | | | |")
		for mission in missions:
			activity = ACTIVITIES.get(mission["slug"], {})
			lines.append(
				f"| {day} | `{theme}` | `{mission['slug']}` | {mission['mission_type']} | {mission['skill'].replace('_', ' ')} | "
				f"{', '.join(s.replace('_', ' ') for s in mission['also_practises'])} | `{activity.get('mechanic', '?')}` | "
				f"{activity.get('evidence', '?').replace('_', ' ')} |"
			)
	lines += [
		"",
		"## Coverage matrix (age band x language)",
		"",
		"`yes` means the variation exists with every mandatory field filled (checked by `validate_catalogue()`).",
		"",
		"| Template | " + " | ".join(f"{BAND[a]} {l}" for a in AGE_BANDS for l in LOCALES) + " |",
		"|---|" + "---|" * (len(AGE_BANDS) * len(LOCALES)),
	]
	for mission in MISSIONS:
		cells = []
		for age in AGE_BANDS:
			for locale in LOCALES:
				present = age in mission["ages"] and locale in mission["ages"][age]["locales"]
				cells.append("yes" if present else "**MISSING**")
		lines.append(f"| `{mission['slug']}` | " + " | ".join(cells) + " |")
	lines += ["", "## Each age-specific mission", ""]
	for mission in MISSIONS:
		activity = ACTIVITIES.get(mission["slug"], {})
		lines += [
			f"### {mission['slug']}",
			"",
			f"Theme `{mission['theme']}`, type {mission['mission_type']}, skill: {mission['skill'].replace('_', ' ')}.",
			f"Activity: {activity.get('summary', '')}",
			"",
		]
		lines += ["| Age | English title | Minutes | Materials (English) | Parent involvement | Why it suits the age (rationale) |", "|---|---|---|---|---|---|"]
		for age in AGE_BANDS:
			a = mission["ages"][age]
			en = a["locales"]["en"]
			lines.append(
				f"| {BAND[age]} | {en['title']} | {a['minutes']} | {'; '.join(en['materials'])} | {a['parent_involvement']} | {a['rationale']} |"
			)
		lines.append("")
	lines += [
		"## How each requirement is stored",
		"",
		"| Requirement | Where it lives |",
		"|---|---|",
		"| Unique title, short description | `title`, `description` (per age band and language) |",
		"| Step-by-step instructions | `instructions`: numbered lines, then an **Another way:** line (accessible alternative) |",
		"| Completion criteria + parent verification | `completion_criteria`: what to show, then a final **Parent check:** line (localized label) |",
		"| Required materials, estimated time | `required_materials`, `duration_minutes` |",
		"| Safety notes | `safety_instructions` |",
		"| Mission type, theme | template `mission_type`, `theme` |",
		"| Age band, language | variation `age_band`, `locale` |",
		"| **Skill category, age rationale, parent-involvement note** | **Not stored in the database** (no column; no migration was added). Kept in this catalogue source and in this document. |",
		"",
		"The reviewing parent sees `description + instructions + completion_criteria` as the task description (`task_description()` in `daily_mission_service`).",
		"",
		"## Counts of text by language",
		"",
		"| Language | Variations | Characters of stored text (min / max per variation) |",
		"|---|---|---|",
	]
	for locale in LOCALES:
		sizes = [
			len(p["description"]) + len(p["instructions"]) + len(p["completion_criteria"])
			for m in MISSIONS
			for a in AGE_BANDS
			for p in [variation_payload(m, a, locale)]
		]
		lines.append(f"| {LOCALE_NAME[locale]} | {len(sizes)} | {min(sizes)} / {max(sizes)} |")
	lines += [
		"",
		"## Missing content and open gaps",
		"",
		f"1. **Template target reached: {summary['templates']} templates, 6 per weekday theme, {summary['distinct_activities']} distinct activities.** "
		"A 42-day cooldown can now hold in full for a child who chooses one mission a day, but 42 days of content is still not a year; "
		"after 42 days every mission repeats (see `docs/mission-rotation.md`).",
		"2. **Gujarati and Hindi have not been reviewed by a native-speaking educator** (all 252 versions). "
		"The script, structure and numerals are machine-checked; wording, register and cultural fit are not. Get a review before publishing to children.",
		"3. **No age-fit pilot with children.** Durations and difficulty come from the cited guidance and judgement, not from observation.",
		"4. **No Indic font is bundled in the Flutter apps** (Rubik / Nunito Sans only). Gujarati and Hindi rely on the device's fallback "
		"font; check on a low-end Android device.",
		"5. **Skill category, age rationale, parent-involvement note and the activity registry have no database column.** An additive migration "
		"(`skill_area`, `developmental_purpose`) is the clean fix if the admin should edit them; not done. The admin health view can only verify "
		"activity distinctness for templates whose slug is in this catalogue source; admin-authored templates are listed as *unverified*.",
		"6. **No daily Surprise mission** (`is_surprise` is false everywhere), so no mystery bonus is attached; that touches the reward rules.",
		"7. **The alphabet rule in the Tuesday 11-15 mission is language-specific:** English uses a, b, c; Gujarati and Hindi use the varnamala (ka, kha, ga). It is the same activity, adapted.",
		"8. **Real PostgreSQL verification is blocked** (`tests/schema/baseline.sql` is missing). Seeding, health and rotation were verified on an in-memory SQLite stand-in only.",
		"",
		"## Rollout (a person runs these against the database they choose)",
		"",
		"```",
		"python -m app.cli seed-daily-missions                  # validate only, no database",
		"python -m app.cli seed-daily-missions --apply          # add missing rows, unpublished",
		"# review each template in the admin panel (Missions > View versions), then publish there",
		"python -m app.cli seed-daily-missions --apply --publish  # or publish the new templates directly",
		"python -m app.cli seed-daily-missions --apply --retire-placeholders  # optional: unpublish unedited migration placeholders",
		"```",
		"",
		"**Do not publish the Gujarati and Hindi text to children before a native-speaking educator has reviewed it.** Seeding is unpublished by default for this reason.",
		"",
	]
	return "\n".join(lines)


if __name__ == "__main__":
	OUT.write_text(build(), encoding="utf-8", newline="\n")
	print(f"wrote {OUT}")
