from __future__ import annotations


def _tf(prompt: str, answer: bool, explanation: str) -> dict:
	return {
		"prompt": prompt,
		"question_type": "true_false",
		"explanation": explanation,
		"options": [
			{"text": "सही", "is_correct": answer},
			{"text": "गलत", "is_correct": not answer},
		],
	}


def _single(prompt: str, options: list[str], correct_index: int, explanation: str) -> dict:
	return {
		"prompt": prompt,
		"question_type": "single",
		"explanation": explanation,
		"options": [
			{"text": text, "is_correct": i == correct_index}
			for i, text in enumerate(options)
		],
	}


def _multi(prompt: str, options: list[str], correct_indices: set[int], explanation: str) -> dict:
	return {
		"prompt": prompt,
		"question_type": "multiple",
		"explanation": explanation,
		"options": [
			{"text": text, "is_correct": i in correct_indices}
			for i, text in enumerate(options)
		],
	}


